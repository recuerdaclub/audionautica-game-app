export function t(
  locale: AppLocale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = messages[locale][key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return text
}

export function bootLines(locale: AppLocale): string[] {
  return [
    t(locale, 'boot0'),
    t(locale, 'boot1'),
    t(locale, 'boot2'),
    t(locale, 'boot3'),
    t(locale, 'boot4'),
    t(locale, 'boot5'),
  ]
}

